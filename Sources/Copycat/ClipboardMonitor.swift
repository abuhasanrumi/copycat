import AppKit
import CryptoKit

final class ClipboardMonitor {
    private let store: ClipStore
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    var paused = false

    private let ignoredTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    init(store: ClipStore) {
        self.store = store
    }

    func start() {
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.check() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    /// Call after writing to the pasteboard ourselves so it isn't recorded as a new copy.
    func syncChangeCount() {
        lastChange = NSPasteboard.general.changeCount
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard !paused else { return }

        let types = pb.types ?? []
        if types.contains(where: { ignoredTypes.contains($0) }) { return }

        let app = NSWorkspace.shared.frontmostApplication
        if app?.bundleIdentifier == Bundle.main.bundleIdentifier { return }
        let appName = app?.localizedName ?? "Unknown"
        let bundleID = app?.bundleIdentifier
        if let bundleID, Preferences.ignoredBundleIDs.contains(bundleID) { return }

        @discardableResult
        func make(_ kind: ClipKind, hashInput: Data, _ configure: (inout ClipItem) -> Void) -> String {
            var item = ClipItem(kind: kind, appName: appName, bundleID: bundleID, date: Date(),
                                hash: SHA256.hash(data: hashInput).map { String(format: "%02x", $0) }.joined())
            configure(&item)
            store.add(item)
            return item.hash
        }

        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            make(.file, hashInput: Data(("file:" + paths.joined(separator: "\n")).utf8)) { $0.filePaths = paths }
            return
        }

        let hasString = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty == false
        if !hasString, let image = readImage(pb) {
            guard let file = store.saveImage(image.png) else { return }
            let hash = make(.image, hashInput: image.png) {
                $0.imageFile = file
                $0.imageWidth = image.width
                $0.imageHeight = image.height
            }
            OCR.recognize(image.png) { [store] text in store.setOCR(hash: hash, text: text) }
            return
        }

        if let s = pb.string(forType: .string), hasString {
            let result = Classifier.classify(s)
            let sensitive = Classifier.isSensitive(s)
            let hash = make(result.kind, hashInput: Data(("text:" + s).utf8)) {
                $0.text = s
                $0.language = result.language
                if sensitive { $0.sensitive = true }
            }
            if result.kind == .link, !sensitive, Preferences.fetchLinkPreviews,
               let url = URL(string: s.trimmingCharacters(in: .whitespacesAndNewlines)) {
                LinkPreviewer.fetch(url) { [store] title, png in store.updateLink(hash: hash, title: title, png: png) }
            }
        }
    }

    private func readImage(_ pb: NSPasteboard) -> (png: Data, width: Int, height: Int)? {
        let raw = pb.data(forType: .png) ?? pb.data(forType: .tiff)
        guard let raw, let rep = NSBitmapImageRep(data: raw),
              let png = rep.representation(using: .png, properties: [:]) else { return nil }
        return (png, rep.pixelsWide, rep.pixelsHigh)
    }
}
